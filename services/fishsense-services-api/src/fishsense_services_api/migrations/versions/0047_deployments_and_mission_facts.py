"""Deployments, and what a mission knows about itself (PLAN.md §4.9, Phase 2b).

**Deployments.** A deployment is one field trip: e4e-data-management's
*dataset* (``YYYY.MM.DD.PROJECT.LOCATION``), holding missions across expedition
days. It is where a trip's shared facts belong (water, borrowed calibrations).
``missions.deployment_id`` is nullable: ~496 of production's 525 missions
predate e4edm and belong to no recorded trip, and grouping them is a dry-run
tool's job, not this migration's. Bare "deployment" means this; a Kubernetes
object is always a "processor Deployment" (CLAUDE.md).

**A mission's purpose** (``survey``, ``lens_calibration``, ``laser_calibration``,
``slate``, ``known_length``, ``other``) decides which stages use it. NULL means
nobody has said: legacy missions until the backfill's inferred purposes are
reviewed, and ingests that did not state one.

**The port is a per-mission fact with provenance**, never a device property:
the same camera body moves between ports. The owner's rules (2026-10-16):

* every mission already ingested is the corrective optic (``backfill``);
* a device labelled with the ``D`` suffix (``FSL-10D``) is the corrective optic
  (``device_suffix``);
* an operator may assert one (``operator``), and a lens calibration may imply
  one (``calibration``: an underwater focal length ~1.31-1.33x the in-air value
  is a bare flat port);
* **nothing else is known.** A missing ``D`` does not mean flat; lab data holds
  bare-flat-port frames that were never reliably labelled.

So the default is ``unknown``, and a known port without a source -- or an
unknown one claiming a source -- is refused by the database. Stages are to
refuse ``unknown`` (a flat port is an axial camera; measured as pinhole its
lengths are silently wrong); that gate lands after the backfill is reviewed
and applied, so this migration changes no stage's cohort. ``port_note`` says
who or what, in words (the rule's date, an operator, a calibration id).

**Place and raw metadata.** ``country``, ``region`` and ``site`` are e4edm's,
stored as written (``region`` is free text: "San Diego" and "SanDiego" both
occur). ``source_metadata`` keeps a mission's ``metadata.json`` verbatim.

Revision ID: 0047
Revises: 0046
"""

from alembic import context, op

revision = "0047"
down_revision = "0046"

ACTIVE_TENANT = "NULLIF(current_setting('app.tenant_id', true), '')::uuid"
PURPOSES = (
    "survey",
    "lens_calibration",
    "laser_calibration",
    "slate",
    "known_length",
    "other",
)
PORTS = ("corrective_optic", "flat", "dome", "unknown")
PORT_SOURCES = ("backfill", "device_suffix", "operator", "calibration")


def _app_role() -> str:
    role = context.config.attributes["app_role"]
    return op.get_bind().dialect.identifier_preparer.quote(role)


def _values(values) -> str:
    return ", ".join(f"'{v}'" for v in values)


def upgrade() -> None:
    op.execute("""
        CREATE TABLE deployments (
            id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
            tenant_id uuid NOT NULL REFERENCES tenants (id) ON DELETE CASCADE,
            number bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
            name text NOT NULL,
            source_path text,
            started_on date,
            ended_on date,
            readme text,
            notes text,
            created_at timestamptz NOT NULL DEFAULT now(),
            UNIQUE (tenant_id, id),
            UNIQUE (tenant_id, name),
            UNIQUE (tenant_id, source_path),
            CONSTRAINT deployments_dates_check CHECK (ended_on >= started_on)
        )
        """)
    op.execute("ALTER TABLE deployments ENABLE ROW LEVEL SECURITY")
    op.execute("ALTER TABLE deployments FORCE ROW LEVEL SECURITY")
    op.execute(f"""
        CREATE POLICY tenant_isolation ON deployments
            USING (tenant_id = {ACTIVE_TENANT})
            WITH CHECK (tenant_id = {ACTIVE_TENANT})
        """)
    op.execute(f"GRANT SELECT, INSERT, UPDATE ON deployments TO {_app_role()}")

    op.execute(f"""
        ALTER TABLE missions
            ADD COLUMN deployment_id uuid,
            ADD COLUMN purpose text
                CONSTRAINT missions_purpose_check
                CHECK (purpose IN ({_values(PURPOSES)})),
            ADD COLUMN port text NOT NULL DEFAULT 'unknown'
                CONSTRAINT missions_port_check CHECK (port IN ({_values(PORTS)})),
            ADD COLUMN port_source text,
            ADD COLUMN port_note text,
            ADD COLUMN country text,
            ADD COLUMN region text,
            ADD COLUMN site text,
            ADD COLUMN source_metadata jsonb,
            ADD CONSTRAINT missions_port_source_check CHECK (
                CASE WHEN port = 'unknown' THEN port_source IS NULL
                     ELSE port_source IS NOT NULL
                          AND port_source IN ({_values(PORT_SOURCES)})
                END
            ),
            ADD CONSTRAINT missions_tenant_id_deployment_id_fkey
                FOREIGN KEY (tenant_id, deployment_id)
                REFERENCES deployments (tenant_id, id)
        """)
    op.execute("""
        CREATE INDEX missions_tenant_id_deployment_id_idx
            ON missions (tenant_id, deployment_id)
        """)


def downgrade() -> None:
    op.execute("""
        ALTER TABLE missions
            DROP COLUMN deployment_id,
            DROP COLUMN purpose,
            DROP COLUMN port,
            DROP COLUMN port_source,
            DROP COLUMN port_note,
            DROP COLUMN country,
            DROP COLUMN region,
            DROP COLUMN site,
            DROP COLUMN source_metadata
        """)
    op.execute("DROP TABLE deployments")
